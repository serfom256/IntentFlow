package io.github.serfom256.intentflow.examples.shop.openmapper;

import io.github.serfom256.annotations.entity.EnumType;
import io.github.serfom256.annotations.entity.Model;
import io.github.serfom256.intentflow.core.catalog.annotation.IntentService;
import io.github.serfom256.intentflow.examples.shop.store.CrudStore;
import io.github.serfom256.mappers.ColumnTypeRegistry;
import io.github.serfom256.model.operations.DmlOperation;
import io.github.serfom256.procedures.Procedures;
import org.jspecify.annotations.Nullable;

import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.function.Function;
import java.util.stream.Collectors;

final class OpenMapperStore<T, E> implements CrudStore<T> {

    private record Column(Field field, String name, EnumType enumType) {
    }

    private final Procedures procedures;
    private final ColumnTypeRegistry columnTypes;
    private final Class<E> type;
    private final Function<T, E> toEntity;
    private final Function<E, T> toDomain;
    private final List<Column> columns;
    private final String key;
    private final String selectAll;
    private final String selectPage;
    private final String selectOne;
    private final String count;
    private final String exists;
    private final String insert;
    private final String update;
    private final String delete;

    OpenMapperStore(Procedures procedures, ColumnTypeRegistry columnTypes, Class<E> type, Function<T, E> toEntity,
            Function<E, T> toDomain) {
        this.procedures = procedures;
        this.columnTypes = columnTypes;
        this.type = type;
        this.toEntity = toEntity;
        this.toDomain = toDomain;
        this.columns = columns(type);
        this.key = type.getAnnotation(Model.class).primaryKey();
        IntentService service = type.getAnnotation(IntentService.class);
        String table = service.table();
        String byKey = " WHERE " + key + " = [" + key + "]";
        String order = " ORDER BY " + String.join(", ", service.defaultSort());
        List<String> values = columns.stream().map(Column::name).filter(name -> !name.equals(key)).toList();
        this.selectAll = "SELECT * FROM " + table + order;
        this.selectPage = selectAll + " LIMIT [limit] OFFSET [offset]";
        this.selectOne = "SELECT * FROM " + table + byKey;
        this.count = "SELECT count(*) FROM " + table;
        this.exists = count + byKey;
        this.insert = "INSERT INTO " + table + " (" + String.join(", ", values) + ") VALUES ("
                + values.stream().map(name -> "[" + name + "]").collect(Collectors.joining(", ")) + ")";
        this.update = "UPDATE " + table + " SET "
                + values.stream().map(name -> name + " = [" + name + "]").collect(Collectors.joining(", ")) + byKey;
        this.delete = "DELETE FROM " + table + byKey;
    }

    @Override
    public List<T> findPage(int page, int size) {
        return procedures.select(selectPage, type, Map.of("limit", size, "offset", page * size)).stream().map(toDomain)
                .toList();
    }

    @Override
    public long count() {
        return procedures.selectOne(count, Long.class).orElse(0L);
    }

    @Override
    public List<T> findAll() {
        return procedures.select(selectAll, type).stream().map(toDomain).toList();
    }

    @Override
    public Optional<T> findById(long id) {
        return procedures.selectOne(selectOne, type, byKey(id)).map(toDomain);
    }

    @Override
    public boolean exists(long id) {
        return procedures.selectOne(exists, Long.class, byKey(id)).orElse(0L) > 0;
    }

    @Override
    public long insert(T value) {
        return procedures.executeReturningKey(insert, DmlOperation.INSERT, Long.class, parameters(value))
                .orElseThrow(() -> new IllegalStateException("No key generated by: " + insert));
    }

    @Override
    public boolean update(T value) {
        return procedures.execute(update, DmlOperation.UPDATE, parameters(value)) > 0;
    }

    @Override
    public boolean delete(long id) {
        return procedures.execute(delete, DmlOperation.DELETE, byKey(id)) > 0;
    }

    private Map<String, Object> byKey(long id) {
        return Map.of(key, id);
    }

    private Map<String, Object> parameters(T value) {
        E entity = toEntity.apply(value);
        Map<String, Object> parameters = new HashMap<>();
        for (Column column : columns) {
            parameters.put(column.name(), bindable(read(column.field(), entity), column.enumType()));
        }
        return parameters;
    }

    private @Nullable Object bindable(@Nullable Object value, EnumType enumType) {
        return value == null ? null : columnTypes.toParameter(value, enumType);
    }

    private static @Nullable Object read(Field field, Object entity) {
        try {
            return field.get(entity);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException("Cannot read " + field, e);
        }
    }

    private static List<Column> columns(Class<?> type) {
        List<Column> columns = new ArrayList<>();
        for (Field field : type.getDeclaredFields()) {
            io.github.serfom256.annotations.entity.Field column = field
                    .getAnnotation(io.github.serfom256.annotations.entity.Field.class);
            if (column != null && !column.readOnly()) {
                field.setAccessible(true);
                columns.add(new Column(field, column.name().isEmpty() ? field.getName() : column.name(),
                        column.enumType()));
            }
        }
        return List.copyOf(columns);
    }
}
